/**
 * ==============================================================================
 * CarbonTrack Production Build & Environment Injector (build-env.js)
 * ------------------------------------------------------------------------------
 * Automatically generates 'carbontrack/env.js' during CI/CD build steps
 * (e.g. Netlify, Vercel, Render, Cloudflare Pages, Docker).
 * 
 * Usage:
 *   node build-env.js
 * ==============================================================================
 */

const fs = require('fs');
const path = require('path');

// 1. Read environment variables from process.env (injected by Vercel/Netlify/CI)
// or parse from local .env if present
let envVars = {};

const envPath = path.resolve(__dirname, '.env');
if (fs.existsSync(envPath)) {
    try {
        const envContent = fs.readFileSync(envPath, 'utf8');
        envContent.split(/\r?\n/).forEach(line => {
            const trimmed = line.trim();
            if (trimmed && !trimmed.startsWith('#')) {
                const match = trimmed.match(/^([^=]+)=(.*)$/);
                if (match) {
                    const key = match[1].trim();
                    let val = match[2].trim();
                    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
                        val = val.slice(1, -1);
                    }
                    envVars[key] = val;
                }
            }
        });
    } catch (err) {
        console.warn('Warning: Could not parse .env file:', err.message);
    }
}

const supabaseUrl = process.env.SUPABASE_URL || envVars.SUPABASE_URL || 'https://your-project.supabase.co';
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY || envVars.SUPABASE_ANON_KEY || 'your-anon-publishable-key-here';

// 2. Generate carbontrack/env.js
const targetDir = path.resolve(__dirname, 'carbontrack');
const targetFile = path.join(targetDir, 'env.js');

const jsContent = `// ==============================================================================
// Auto-generated by build-env.js during deployment
// DO NOT COMMIT THIS FILE TO GIT
// ==============================================================================
window.__ENV__ = {
    SUPABASE_URL: "${supabaseUrl}",
    SUPABASE_ANON_KEY: "${supabaseAnonKey}"
};
`;

try {
    if (!fs.existsSync(targetDir)) {
        fs.mkdirSync(targetDir, { recursive: true });
    }
    fs.writeFileSync(targetFile, jsContent, 'utf8');
    console.log(`[build-env] Successfully generated ${targetFile}`);
    console.log(`[build-env] Configured SUPABASE_URL: ${supabaseUrl}`);
} catch (err) {
    console.error('[build-env] Failed to generate env.js:', err);
    process.exit(1);
}
